// Isolated synthetic batch only. No real company data, no reviewer reports.
// Run from the project root; the destination must be a new directory.
import {registerHooks} from 'node:module';
import {mkdir, mkdtemp, readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';

registerHooks({resolve(specifier,context,next){
 if(specifier==='server-only')return {url:'data:text/javascript,export default {}',shortCircuit:true};
 if(context.parentURL?.includes('/app/lib/') && specifier.startsWith('.') && !/\.[cm]?[jt]sx?$/.test(specifier))
  return next(new URL(specifier+'.ts',context.parentURL).href,context);
 return next(specifier,context);
}});
const root=path.resolve('work/dual-agent-synthetic');
await mkdir(root,{recursive:true,mode:0o700});
const run=await mkdtemp(path.join(root,'batch-'));
const input=path.join(run,'inputs'),output=path.join(run,'outputs');
await mkdir(input,{mode:0o700});await mkdir(output,{mode:0o700});
process.env.ALLOCATION_DATA_DIR=path.join(run,'database');

// Excel files are generated by the already-vetted synthetic fixture generator.
await import('./make-browser-fixtures.mjs');
const sourceDir=path.resolve('work/browser-fixtures');
const source1=await readFile(path.join(sourceDir,'source1.xlsx'));
const source2=await readFile(path.join(sourceDir,'source2.xlsx'));
const tax=await readFile(path.join(sourceDir,'tax.xlsx'));
const template=await readFile(path.join(sourceDir,'template.xlsx'));
await writeFile(path.join(input,'source1.xlsx'),source1);
await writeFile(path.join(input,'source2.xlsx'),source2);
await writeFile(path.join(input,'tax.xlsx'),tax);
await writeFile(path.join(input,'template.xlsx'),template);
const workflow=await import(new URL('../app/lib/workflow.ts',import.meta.url).href);
const persistence=await import(new URL('../app/lib/persistence.ts',import.meta.url).href);
await workflow.importSource(source1,'source1.xlsx',0,'synthetic',{priority:1});
await workflow.importSource(source2,'source2.xlsx',1,'synthetic',{
  priority:2,
  independentConfirmed:true,
  sourceReference:'SYNTHETIC-SOURCE-2',
});
await workflow.importTax(tax,'tax.xlsx',2,'synthetic');
const batch=await workflow.prepareBatch({product:'合成测试商品',price:'33',quantity:3,version:3},template,'template.xlsx','synthetic');
const bundle=await workflow.reviewBundle(batch.id);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const exported=[];
for(const [index,entry] of bundle.manifest.entries()){
 const object=await persistence.readFile(entry.key);
 if(!object || sha(object.bytes)!==entry.sha256)throw new Error('Synthetic result hash mismatch');
 const filename=`${String(index+1).padStart(2,'0')}_${entry.name}`;
 await writeFile(path.join(output,filename),object.bytes);
 exported.push({filename,role:entry.role,sourceId:entry.sourceId,sha256:entry.sha256,key:entry.key});
}
await writeFile(path.join(run,'review-bundle.json'),JSON.stringify(bundle,null,2));
await writeFile(path.join(run,'exported-files.json'),JSON.stringify(exported,null,2));
const summary=await workflow.stateSummary();
if(summary.version!==3 || batch.status!=='awaiting_review' || bundle.reviewStatus.submitted!==false)throw new Error('Unexpected synthetic pre-review state');
console.log(JSON.stringify({synthetic:true,run,batchId:batch.id,reviewDigest:bundle.reviewDigest,files:exported.length,workspaceVersion:summary.version,status:batch.status}));
